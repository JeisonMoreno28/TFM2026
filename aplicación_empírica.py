def calibrar_bs(S, K_arr, T, r, p_mkt):
    res = minimize(lambda p: sum((bs_call(S,K,T,r,p[0])-pm)**2
                                 for K,pm in zip(K_arr,p_mkt)),
                   [0.20], method='Nelder-Mead',
                   options={'xatol':1e-8,'fatol':1e-10,'maxiter':5000})
    return res.x[0], res.fun


