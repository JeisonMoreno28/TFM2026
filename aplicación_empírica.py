def descargar_opciones():
    """Descarga opciones SPY a ~90 días vía yfinance."""
    try:
        import yfinance as yf
        from datetime import datetime, timedelta
        spy  = yf.Ticker("SPY")
        S0   = spy.history(period="1d")["Close"].iloc[-1]
        exps = spy.options
        hoy  = datetime.today()
        exp  = min(exps, key=lambda d: abs(
                   datetime.strptime(d,"%Y-%m-%d")-(hoy+timedelta(days=90))))
        T     = (datetime.strptime(exp,"%Y-%m-%d")-hoy).days/365.0
        chain = spy.option_chain(exp).calls
        chain = chain[(chain["impliedVolatility"]>0.01) &
                      (chain["impliedVolatility"]<2.0)  &
                      (chain["volume"]>10) &
                      (chain["strike"]>0.80*S0) &
                      (chain["strike"]<1.20*S0)]
        chain["mid"] = (chain["bid"]+chain["ask"])/2
        chain = chain[chain["mid"]>0.05]
        print(f"✓ Datos reales SPY: S0={S0:.2f}, exp={exp}, n={len(chain)}")
        return S0, 0.05, T, chain[["strike","mid"]].reset_index(drop=True)
    except Exception as e:
        print(f"✗ Sin datos reales ({e}). Usando referencia de literatura.")
        return None

