def calibrar_heston(S, K_arr, T, r, p_mkt):

    def obj(p):
        kappa, theta, sv, rho, v0 = p
        if (kappa <= 0 or theta <= 0 or sv <= 0
                or v0 < 0.001
                or abs(rho) >= 1):
            return 1e10
        pen = max(0, sv**2 - 2*kappa*theta) * 1e4
        try:
            pm = heston_call_vec(S, K_arr, T, r,
                                  kappa, theta, sv, rho, v0)
            w  = 1.0 / np.maximum(p_mkt, 1e-4)
            return float(np.sum(w * (pm - p_mkt)**2)) + pen
        except Exception:
            return 1e10

    idx_atm = np.argmin(np.abs(K_arr - S))
    sigma0  = np.clip(np.sqrt(2*np.pi/T) * p_mkt[idx_atm] / S,
                      0.05, 0.80)
    v0_est  = sigma0**2

    v0_est = max(v0_est, 0.01)

    starts = [
        [1.0,  v0_est,       sigma0*0.3,  -0.7,  v0_est      ],
        [2.0,  v0_est,       sigma0*0.5,  -0.5,  v0_est      ],
        [0.5,  v0_est*1.2,   sigma0*0.2,  -0.8,  v0_est      ],
        [3.0,  v0_est*0.8,   sigma0*0.4,  -0.6,  v0_est*0.8  ],
        [1.5,  v0_est,       sigma0*0.15, -0.4,  v0_est*1.2  ],
        [4.0,  v0_est*0.5,   sigma0*0.6,  -0.9,  v0_est*0.5  ],
        [0.8,  v0_est*1.5,   sigma0*0.25, -0.3,  v0_est*1.5  ],
    ]

    mejor_val    = np.inf
    mejor_params = starts[0]

    for x0 in starts:
        res = minimize(obj, x0, method='Nelder-Mead',
                       options={'xatol':1e-4, 'fatol':1e-4,
                                'maxiter':2000, 'adaptive':True})
        if res.fun < mejor_val:
            mejor_val    = res.fun
            mejor_params = res.x

    # ── refinamiento desde el mejor punto ─────────────
    res_final = minimize(obj, mejor_params, method='Nelder-Mead',
                         options={'xatol':1e-7, 'fatol':1e-9,
                                  'maxiter':5000, 'adaptive':True})

    return res_final.x, res_final.fun

def calibrar_vasicek(S, K_arr, T, r, p_mkt, hp):
    from scipy.optimize import minimize

    kappa, theta, sv, rho, v0 = hp

    def obj(p):
        a, b, sr = p
        try:
            pm = np.array([vh_call_approx(S, K, T, r,
                                           kappa, theta, sv, rho, v0,
                                           a, b, sr)
                           for K in K_arr])
            w = 1.0 / np.maximum(p_mkt, 1e-4)
            return float(np.sum(w * (pm - p_mkt)**2))
        except Exception:
            return 1e10

    # Bounds estrictos
    # a  ∈ [0.01, 5.0]  : reversión lenta a rápida (no instantánea)
    # b  ∈ [0.001, 0.15] : tipo largo plazo entre 0.1% y 15%
    # sr ∈ [0.001, 0.05] : vol del tipo entre 0.1% y 5%
    bounds = [(0.01, 5.0),
              (0.001, 0.15),
              (0.001, 0.05)]

    # Múltiples puntos iniciales nos evitan mínimos locales
    starts = [
        [0.5,  r,     0.01],
        [1.0,  r,     0.02],
        [2.0,  r,     0.005],
        [0.2,  r*1.1, 0.015],
        [3.0,  r*0.9, 0.03],
    ]

    mejor_val    = np.inf
    mejor_params = starts[0]

    for x0 in starts:
        try:
            res = minimize(obj, x0,
                           method='L-BFGS-B',
                           bounds=bounds,
                           options={'ftol':1e-9,
                                    'gtol':1e-7,
                                    'maxiter':2000})
            if res.fun < mejor_val:
                mejor_val    = res.fun
                mejor_params = res.x
        except Exception:
            pass

    return np.array(mejor_params), mejor_val

