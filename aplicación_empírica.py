def bs_call(S, K, T, r, sig):
    d1 = (np.log(S/K)+(r+0.5*sig**2)*T)/(sig*np.sqrt(T))
    d2 = d1 - sig*np.sqrt(T)
    return S*norm.cdf(d1) - K*np.exp(-r*T)*norm.cdf(d2)

def heston_cf(u, S, T, r, kappa, theta, sv, rho, v0):
    i = 1j
    xi  = kappa - rho * sv * i * u
    d   = np.sqrt(xi**2 + sv**2 * u * (u + i))
    g   = (xi - d) / (xi + d)
    edt = np.exp(-d * T)
    C = (r * i * u * T
         + kappa * theta / sv**2
           * ((xi - d) * T - 2 * np.log((1 - g * edt) / (1 - g))))
    D = (xi - d) / sv**2 * (1 - edt) / (1 - g * edt)
    return np.exp(C + D * v0 + i * u * np.log(S * np.exp(r * T)))


def heston_integrand(u, lnK_arr, S, T, r, kappa, theta, sv, rho, v0):
    # P2: phi evaluada en u
    phi2 = heston_cf(u, S, T, r, kappa, theta, sv, rho, v0)
    # P1: phi evaluada en u - i  (cambio de numerario)
    phi1 = heston_cf(u - 1j, S, T, r, kappa, theta, sv, rho, v0)
    phi1_0 = heston_cf(-1j,  S, T, r, kappa, theta, sv, rho, v0)

    # e^{-iu ln K} para cada strike simultáneamente
    e_lnK = np.exp(-1j * u * lnK_arr)

    I2 = np.real(e_lnK * phi2  / (1j * u))      # integrando P2
    I1 = np.real(e_lnK * phi1  / (1j * u * phi1_0))  # integrando P1

    return np.concatenate([I2, I1])

def heston_call_vec(S, K_arr, T, r, kappa, theta, sv, rho, v0,
                    upper=150):
    K_arr = np.asarray(K_arr)
    n     = len(K_arr)
    lnK   = np.log(K_arr)

    result, _ = quad_vec(
        lambda u: heston_integrand(u, lnK, S, T, r,
                                  kappa, theta, sv, rho, v0),
        1e-5, upper,
        epsabs=1e-5, epsrel=1e-5
    )

    I2 = result[:n]
    I1 = result[n:]

    P2 = 0.5 + I2 / np.pi
    P1 = 0.5 + I1 / np.pi

    precios = S * P1 - K_arr * np.exp(-r * T) * P2
    floor   = np.maximum(S - K_arr * np.exp(-r * T), 0)
    return np.maximum(precios, floor)


def heston_call(S, K, T, r, kappa, theta, sv, rho, v0):
    """
    Precio call europea bajo Heston vía inversión de Fourier
    (Gil-Pelaez 1951, Heston 1993).
    """
    lnK = np.log(K)
    def I(u, j):
        phi = heston_cf(u-(1j if j==1 else 0), S, T, r, kappa, theta, sv, rho, v0)
        p0  = heston_cf(-(1j if j==1 else 0),  S, T, r, kappa, theta, sv, rho, v0)
        return np.real(np.exp(-1j*u*lnK)*phi/(1j*u*p0))
    P1,_ = quad(lambda u: I(u,1), 1e-5, 150, limit=80)
    P2,_ = quad(lambda u: I(u,2), 1e-5, 150, limit=80)
    return max(S*(0.5+P1/np.pi) - K*np.exp(-r*T)*(0.5+P2/np.pi),
               max(S-K*np.exp(-r*T), 0))

def vasicek_bond(r0, T, a, b, sr):
    """Precio bono cupón cero bajo Vasicek"""
    B = (1-np.exp(-a*T))/a
    bstar = b - sr**2/(2*a**2)
    A = bstar*(B-T) - sr**2/(4*a)*B**2
    return np.exp(A + B*r0)

def vh_call_approx(S, K, T, r0, kappa, theta, sv, rho, v0,
                   a, b, sr):
    """
    Precio call bajo Vasicek-Heston.
    """
    P    = vasicek_bond(r0, T, a, b, sr)
    r_fw = -np.log(P) / T

    var_adj = sr**2 / (2*a**3) * (
        2*a*T - 3 + 4*np.exp(-a*T) - np.exp(-2*a*T))

    # Ajuste máximo: no más del 50% de la varianza original
    var_adj = np.clip(var_adj, 0, 0.5 * sv**2)
    sv_adj  = np.sqrt(sv**2 + var_adj)

    # Precio Heston con tasa forward y vol ajustada
    p_hes = heston_call_vec(S, np.array([K]), T, r_fw,
                             kappa, theta, sv_adj, rho, v0)[0]

    # Reescalar por el ratio de factores de descuento
    factor = np.exp(-r0*T) / np.exp(-r_fw*T)
    precio  = p_hes * factor

    floor = max(S - K*np.exp(-r0*T), 0.0)
    return max(float(precio), floor)

